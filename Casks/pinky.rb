cask "pinky" do
  arch arm: "arm64", intel: "amd64"

  version "2026.1108.5"
  sha256 arm:   "a79215aed90f63757a57b61b9d227cf38b466b1188d1c858315e5a492d6cc265",
         intel: "1ca69e8bc083c08449b8b5e985e1fac350be7ecb7835c8ac1b57f613e1d6d411"

  url "https://github.com/DIYgod/pinky/releases/download/v#{version}/pinky-#{version}-darwin-#{arch}.zip"
  name "Pinky"
  desc "Let AI agents use your phone, with you in the loop"
  homepage "https://github.com/DIYgod/pinky"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
