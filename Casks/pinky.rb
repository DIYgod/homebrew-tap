cask "pinky" do
  arch arm: "arm64", intel: "amd64"

  version "2026.1108.9"
  sha256 arm:   "6262d39f75d52a60185e1c9dc04db9750524ed85da4e1bb7c020e176a7e5045f",
         intel: "3b5c685b7959e6f22d0c7b3bac60d0bddf4e6923c23d80c6bd98b223add9c92e"

  url "https://github.com/DIYgod/pinky/releases/download/v#{version}/pinky-#{version}-darwin-#{arch}.zip"
  name "Pinky"
  desc "Let AI agents use your phone, with you in the loop"
  homepage "https://github.com/DIYgod/pinky"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
  depends_on macos: :monterey

  app "Pinky.app"
